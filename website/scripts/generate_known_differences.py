"""Write the catalogue of known differences on the Known differences page from SQLQuack's entries.

The entries, `KNOWN_DIFFERENCES` in `crates/sqlquack-policy/src/known_differences/constants.rs`,
say for each known difference what differs, when relying on it is fine, when it is wrong and how
it fails; `crates/sqlquack-policy/policy.toml` gives each one's default. This script writes them
between the generated markers of `website/src/content/docs/docs/known-differences.mdx`: first the
ones that can return a different value, then the ones that raise an error instead, by area. With
`--check` it writes nothing and exits 1 when the page differs from what the entries give.

Usage: python3 scripts/generate_known_differences.py [--check]   (from website/)
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

from generate_diagnostics import STRING, cell, literal, prose

WEBSITE = Path(__file__).resolve().parent.parent
POLICY = WEBSITE.parent / "crates/sqlquack-policy/src"
ENTRIES = POLICY / "known_differences/constants.rs"
DEFAULTS = POLICY.parent / "policy.toml"
PAGE = WEBSITE / "src/content/docs/docs/known-differences.mdx"

BEGIN = (
    "{/* Generated by website/scripts/generate_known_differences.py from\n"
    "    crates/sqlquack-policy/src/known_differences/constants.rs. Edit the entries, then rerun"
    " it. */}"
)
END = "{/* End of the generated known differences. */}"

CONSTANT = re.compile(r"pub const (\w+): &str =\s*" + STRING + r";", re.S)
ENTRY = re.compile(r"KnownDifference \{(.*?)\}", re.S)
FIELD = re.compile(r"(\w+):\s*(Some\(\s*" + STRING + r",?\s*\)|None|" + STRING + r"|[\w:]+),", re.S)
FIELDS = ("name", "title", "differs", "fine_when", "wrong_when", "failure")
# How each failure mode shows to a user; the mode names themselves stay internal.
FAILS_WITH = {"Value": "a different value", "Loud": "an error"}
DEFAULT = {"allow": "allowed", "refuse": "refused"}
# What every entry that fails with an error says at the end of `wrong_when`; the page says it once.
RAISES = ": DuckDB raises an error where Snowflake returns a value, never a different value."
# The area each known difference that fails with an error is listed under, in page order.
AREAS = {
    "Numbers": ("numeric_range", "text_number_scale", "float_decimal_digits"),
    "Text": ("text_similarity", "case_folding", "regexp_pattern_syntax", "initcap_text"),
    "Dates and times": (
        "time_zone_spelling",
        "timestamp_tz_offset",
        "date_text_spelling",
        "timestamp_range",
        "timestamp_tz_submicro",
        "time_submicro",
        "timestamp_text_rounding",
    ),
    "VARIANT and JSON": ("array_sort_order", "json_fidelity", "variant_typed_values", "float_text"),
    "Aggregates and ordering": (
        "percentile_interpolation",
        "mode_of_no_rows",
        "float_sum_order",
        "extreme_key_ties",
        "mode_ties",
        "array_agg_order",
        "listagg_order",
        "any_value_choice",
    ),
    "Python and project": ("python_value_crossing",),
}


def constants() -> dict[str, str]:
    """Every `&str` constant the entries may name, from every source file of the policy crate."""
    found: dict[str, str] = {}
    for path in sorted(POLICY.rglob("*.rs")):
        found.update((name, literal(value)) for name, value in CONSTANT.findall(path.read_text()))
    return found


def entries(source: str, named: dict[str, str]) -> list[dict[str, str]]:
    """Every entry in table order, with constant names resolved; fails on a missing field."""
    table = source.split("pub const KNOWN_DIFFERENCES", 1)[1]
    found = []
    for body in ENTRY.findall(table):
        entry: dict[str, str] = {}
        for name, raw, some, text in FIELD.findall(body):
            if raw == "None":
                continue
            if raw.startswith("Some("):
                entry[name] = literal(some)
            elif raw.startswith('"'):
                entry[name] = literal(text)
            elif name == "failure":
                entry[name] = FAILS_WITH[raw.rsplit("::", 1)[-1]]
            else:
                entry[name] = named[raw.rsplit("::", 1)[-1]]
        missing = [field for field in FIELDS if field not in entry]
        if missing:
            raise SystemExit(f"{ENTRIES}: an entry lacks {', '.join(missing)}: {body.strip()}")
        found.append(entry)
    return found


def defaults() -> dict[str, str]:
    """Each known difference's built-in default, "allowed" or "refused"."""
    divergences = tomllib.loads(DEFAULTS.read_text())["divergences"]
    return {name: DEFAULT[entry["default"]] for name, entry in divergences.items()}


def section(entry: dict[str, str], default: str, level: str) -> list[str]:
    """One known difference under a heading whose anchor is its name."""
    wrong = entry["wrong_when"]
    if wrong.endswith(RAISES):
        wrong = wrong[: -len(RAISES)] + "."
    return [
        "",
        f"{level} `{entry['name']}`",
        "",
        f"**{prose(entry['title'].rstrip('.'))}.** {default.capitalize()} by default.",
        "",
        f"- **What differs:** {prose(entry['differs'])}",
        f"- **Fine when:** {prose(entry['fine_when'])}",
        f"- **Wrong when:** {prose(wrong)}",
    ]


def table(known: list[dict[str, str]], default: dict[str, str]) -> list[str]:
    """The ones that can return a different value, then the ones that raise an error, by area."""
    value = [entry for entry in known if entry["failure"] == FAILS_WITH["Value"]]
    loud = {entry["name"]: entry for entry in known if entry["failure"] == FAILS_WITH["Loud"]}
    listed = [name for names in AREAS.values() for name in names]
    unlisted = sorted(set(loud) - set(listed))
    stray = sorted(set(listed) - set(loud))
    if unlisted or stray:
        raise SystemExit(
            f"AREAS in {__file__} needs updating: no area for {unlisted}; "
            f"not an entry that fails with an error: {stray}"
        )
    lines = [
        BEGIN,
        "",
        "## Can return a different value",
        "",
        "Where one of these doesn't hold, the converted SQL returns a value that differs from"
        " Snowflake's, with no error. Read its entry before you allow it.",
        "",
        "| Known difference | Name | Default |",
        "|------------------|------|---------|",
    ]
    for entry in value:
        lines.append(
            f"| [{cell(entry['title'])}](#{entry['name']}) | `{entry['name']}` "
            f"| {default[entry['name']]} |"
        )
    for entry in value:
        lines += section(entry, default[entry["name"]], "###")
    lines += [
        "",
        "## Raise an error instead",
        "",
        "Where one of these doesn't hold, DuckDB raises an error where Snowflake returns a value,"
        " never a different value.",
    ]
    for area, names in AREAS.items():
        lines += ["", f"### {area}"]
        for name in [entry["name"] for entry in known if entry["name"] in names]:
            lines += section(loud[name], default[name], "####")
    return lines + ["", END]


def page(current: str, known: list[dict[str, str]], default: dict[str, str]) -> str:
    """The page with its generated block replaced."""
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + "\n".join(table(known, default)) + current[end:]


def main(argv: list[str]) -> int:
    current = PAGE.read_text()
    wanted = page(current, entries(ENTRIES.read_text(), constants()), defaults())
    if "--check" in argv:
        if current != wanted:
            print(
                f"{PAGE} is out of date; run python3 scripts/generate_known_differences.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE.write_text(wanted)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
