"""Write the diagnostics reference page from SQLQuack's diagnostic code registry.

The registry, `crates/sqlquack-diagnostics/src/diagnostics/constants.rs`, is the one source of
every `SQ` code. This script reads its `CODES` entries and writes
`website/src/content/docs/docs/diagnostics/reference.mdx`. With `--check` it writes nothing and
exits 1 when the page differs from what the registry gives.

Usage: python3 scripts/generate_diagnostics.py [--check]   (from website/)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

WEBSITE = Path(__file__).resolve().parent.parent
REGISTRY = WEBSITE.parent / "crates/sqlquack-diagnostics/src/diagnostics/constants.rs"
PAGE = WEBSITE / "src/content/docs/docs/diagnostics/reference.mdx"

# A Rust string literal, with `\` line continuations and escapes.
STRING = r'"((?:[^"\\]|\\.)*)"'
CONSTANT = re.compile(r"pub const (\w+): &str =\s*" + STRING + r";", re.S)
ENTRY = re.compile(r"CodeEntry \{(.*?)\n    \},", re.S)
RAW = r'r#"(.*?)"#'
FIELD = re.compile(
    r"(\w+): (Some\(\s*" + STRING + r",?\s*\)|None|" + STRING + r"|" + RAW + r"|\w+),", re.S
)

GROUPS = [
    ("SQ00", "Conversion", "Why a statement was not converted."),
    ("SQ01", "Input limits", "Limits that keep parsing and conversion bounded."),
    ("SQ02", "SQL Snowflake rejects", "SQL that parses but that Snowflake rejects when it runs."),
]


def literal(text: str) -> str:
    """The value of a Rust string literal's contents."""
    text = re.sub(r"\\\n\s*", "", text)
    return text.replace('\\"', '"').replace("\\\\", "\\")


def entries(source: str) -> list[dict[str, str | None]]:
    """Every code entry, in registry order, with constant names resolved."""
    constants = {name: literal(value) for name, value in CONSTANT.findall(source)}
    found = []
    for body in ENTRY.findall(source.split("pub const CODES")[1]):
        entry: dict[str, str | None] = {}
        for name, raw, some, plain, verbatim in FIELD.findall(body):
            if raw == "None":
                entry[name] = None
            elif raw.startswith("Some("):
                entry[name] = literal(some)
            elif raw.startswith('"'):
                entry[name] = literal(plain)
            elif raw.startswith('r#"'):
                entry[name] = verbatim
            else:
                entry[name] = constants[raw]
        found.append(entry)
    return found


def cell(text: str) -> str:
    """Text safe inside an MDX table cell."""
    return text.replace("|", "\\|").replace("{", "\\{").replace("<", "&lt;")


def prose(text: str) -> str:
    """Text safe as an MDX paragraph."""
    return text.replace("{", "\\{").replace("<", "&lt;")


def page(codes: list[dict[str, str | None]]) -> str:
    lines = [
        "---",
        'title: "Diagnostic reference"',
        'description: "Every SQLQuack diagnostic code, what it means and how to fix it."',
        "sidebar:",
        '  label: "Reference"',
        "---",
        "",
        "{/* Generated by website/scripts/generate_diagnostics.py from",
        "    crates/sqlquack-diagnostics/src/diagnostics/constants.rs."
        " Edit the registry, then rerun it. */}",
        "",
        "Every diagnostic SQLQuack prints has one of these codes. A code is never reused or",
        "renumbered. See [Reading diagnostics](/docs/diagnostics/overview/) for the output format.",
        "",
        "| Code | Name | Meaning |",
        "|------|------|---------|",
    ]
    for entry in codes:
        lines.append(
            f"| [`{entry['code']}`](#{str(entry['code']).lower()}) | `{entry['name']}` "
            f"| {cell(str(entry['title']))} |"
        )
    for prefix, heading, intro in GROUPS:
        group = [entry for entry in codes if str(entry["code"]).startswith(prefix)]
        if not group:
            continue
        lines += ["", f"## {heading}", "", intro]
        for entry in group:
            lines += [
                "",
                f"### {entry['code']}",
                "",
                f"**{prose(str(entry['title']))}** (`{entry['name']}`)",
            ]
            lines += ["", prose(str(entry["explanation"]))]
            if entry.get("help"):
                lines += ["", f"**Help:** {prose(str(entry['help']))}"]
            example = entry.get("example")
            if example and "sqlquack" in example:
                lines += ["", "**Example:**", "", "```sh", example, "```"]
            elif example:
                lines += ["", f"**Example:** {prose(example)}"]
            if entry.get("alias"):
                lines += ["", f"Also reported by its guard name, `{entry['alias']}`."]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    wanted = page(entries(REGISTRY.read_text()))
    if "--check" in argv:
        if PAGE.read_text() != wanted:
            print(
                f"{PAGE} is out of date; run python3 scripts/generate_diagnostics.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(wanted)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
