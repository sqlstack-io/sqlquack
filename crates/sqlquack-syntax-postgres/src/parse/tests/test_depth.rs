//! Deep nesting in the PostgreSQL parser: refused at the depth limit, never by the thread's stack.

use crate::parse::main::parse::parse;
use crate::parse::main::parse_type::parse_type;
use crate::parse::tests::test_types::NestingTestCase;

/// A thread stack far smaller than the depth limit needs, so passing shows the stack grows on demand.
const SMALL_STACK_BYTES: usize = 256 * 1024;

#[test]
fn given_deep_nesting_when_parsing_on_a_small_stack_then_the_depth_limit_refuses_it() {
    let test_cases = [
        NestingTestCase {
            description: "parenthesized joins in FROM",
            prefix: "SELECT * FROM ",
            open: "(",
            innermost: "a JOIN b ON true",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "derived tables in FROM",
            prefix: "SELECT * FROM ",
            open: "(SELECT * FROM ",
            innermost: "t",
            close: ") s",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "LATERAL subqueries in FROM",
            prefix: "SELECT * FROM t, ",
            open: "LATERAL (SELECT * FROM t, ",
            innermost: "u",
            close: ") s",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "scalar subqueries",
            prefix: "SELECT ",
            open: "(SELECT ",
            innermost: "1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "EXISTS subqueries",
            prefix: "SELECT ",
            open: "EXISTS (SELECT ",
            innermost: "1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "IN subqueries",
            prefix: "SELECT 1 IN ",
            open: "(SELECT 1 IN (",
            innermost: "SELECT 1",
            close: "))",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "parenthesized queries",
            prefix: "",
            open: "(",
            innermost: "SELECT 1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "WITH queries",
            prefix: "",
            open: "WITH a AS (",
            innermost: "SELECT 1",
            close: ") SELECT 1",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "parenthesized expressions",
            prefix: "SELECT ",
            open: "(",
            innermost: "1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "function calls",
            prefix: "SELECT ",
            open: "abs(",
            innermost: "1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "CASE expressions",
            prefix: "SELECT ",
            open: "CASE WHEN true THEN ",
            innermost: "1",
            close: " END",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "array constructors",
            prefix: "SELECT ",
            open: "ARRAY[",
            innermost: "1",
            close: "]",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "unary minus",
            prefix: "SELECT ",
            open: "- ",
            innermost: "1",
            close: "",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "JSON_OBJECT keys, read as c_expr outside the operator climb",
            prefix: "SELECT ",
            open: "json_object(",
            innermost: "1",
            close: " VALUE 1)",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "parenthesized type modifiers in a cast",
            prefix: "SELECT CAST(1 AS ",
            open: "t(",
            innermost: "int",
            close: "))",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "BEGIN ATOMIC function bodies",
            prefix: "",
            open: "CREATE FUNCTION f() RETURNS int BEGIN ATOMIC ",
            innermost: " SELECT 1;",
            close: " END;",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "parenthesized expressions well inside the limit",
            prefix: "SELECT ",
            open: "(",
            innermost: "1",
            close: ")",
            read: |text| parse(text).err(),
            levels: 100,
            expected_error: None,
        },
        NestingTestCase {
            description: "derived tables well inside the limit",
            prefix: "SELECT * FROM ",
            open: "(SELECT * FROM ",
            innermost: "t",
            close: ") s",
            read: |text| parse(text).err(),
            levels: 40,
            expected_error: None,
        },
        NestingTestCase {
            description: "old-style json_object lists, whose three readings each hold the next",
            prefix: "SELECT ",
            open: "json_object(",
            innermost: "1",
            close: ", 1)",
            read: |text| parse(text).err(),
            levels: 60,
            expected_error: None,
        },
        NestingTestCase {
            description: "unclosed IN ((SELECT, each also read as a list holding the next",
            prefix: "SELECT 1 IN (",
            open: "(SELECT 1 IN (",
            innermost: "",
            close: "",
            read: |text| parse(text).err(),
            levels: 60,
            expected_error: Some(("syntax error at end of input", true)),
        },
        NestingTestCase {
            description: "unclosed json_object calls, each read three ways",
            prefix: "SELECT ",
            open: "json_object(",
            innermost: "",
            close: "",
            read: |text| parse(text).err(),
            levels: 60,
            expected_error: Some(("syntax error at end of input", true)),
        },
        NestingTestCase {
            description: "100 nested FROM subqueries, which a 2 MiB thread could not hold before",
            prefix: "SELECT * FROM ",
            open: "(SELECT * FROM ",
            innermost: "t",
            close: ") s",
            read: |text| parse(text).err(),
            levels: 100,
            expected_error: None,
        },
        NestingTestCase {
            description: "parenthesized tables in FROM",
            prefix: "SELECT * FROM ",
            open: "(",
            innermost: "t",
            close: ")",
            read: |text| parse(text).err(),
            levels: 3000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "NOT prefixes",
            prefix: "SELECT ",
            open: "NOT ",
            innermost: "true",
            close: "",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "nested subscripts",
            prefix: "SELECT ",
            open: "a[",
            innermost: "1",
            close: "]",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "[] suffixes on a cast type",
            prefix: "SELECT 1::int",
            open: "[]",
            innermost: "",
            close: "",
            read: |text| parse(text).err(),
            levels: 100000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "[3] suffixes on a CAST type",
            prefix: "SELECT CAST(1 AS int",
            open: "[3]",
            innermost: "",
            close: ")",
            read: |text| parse(text).err(),
            levels: 100000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "[] suffixes on a column type",
            prefix: "CREATE TABLE t (a int",
            open: "[]",
            innermost: "",
            close: ")",
            read: |text| parse(text).err(),
            levels: 100000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "casts nesting array types, each type 60 bounds deep, counted together",
            prefix: "SELECT ",
            open: "CAST(",
            innermost: "1",
            close: " AS int[][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][])",
            read: |text| parse(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "casts nesting array types, few enough levels in all",
            prefix: "SELECT ",
            open: "CAST(",
            innermost: "1",
            close: " AS int[][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][][])",
            read: |text| parse(text).err(),
            levels: 20,
            expected_error: None,
        },
        NestingTestCase {
            description: "1,000 additions, the longest chain",
            prefix: "SELECT 1",
            open: "",
            innermost: "",
            close: " + 1",
            read: |text| parse(text).err(),
            levels: 1000,
            expected_error: None,
        },
        NestingTestCase {
            description: "1,001 additions",
            prefix: "SELECT 1",
            open: "",
            innermost: "",
            close: " + 1",
            read: |text| parse(text).err(),
            levels: 1001,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "100,000 casts in a chain",
            prefix: "SELECT 1",
            open: "",
            innermost: "",
            close: "::int",
            read: |text| parse(text).err(),
            levels: 100000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "100,000 field selections",
            prefix: "SELECT (a)",
            open: "",
            innermost: "",
            close: ".b",
            read: |text| parse(text).err(),
            levels: 100000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "AND chains are not counted",
            prefix: "SELECT true",
            open: "",
            innermost: "",
            close: " AND true",
            read: |text| parse(text).err(),
            levels: 5000,
            expected_error: None,
        },
        NestingTestCase {
            description: "set operations are not counted",
            prefix: "SELECT 1",
            open: "",
            innermost: "",
            close: " UNION ALL SELECT 1",
            read: |text| parse(text).err(),
            levels: 5000,
            expected_error: None,
        },
        NestingTestCase {
            description: "parenthesized type modifiers in a type string",
            prefix: "",
            open: "t(",
            innermost: "int",
            close: ")",
            read: |text| parse_type(text).err(),
            levels: 2000,
            expected_error: Some(("stack depth limit exceeded", false)),
        },
        NestingTestCase {
            description: "parenthesized type modifiers in a type string well inside the limit",
            prefix: "",
            open: "t(",
            innermost: "int",
            close: ")",
            read: |text| parse_type(text).err(),
            levels: 40,
            expected_error: None,
        },
    ];
    for test_case in test_cases {
        let text: String = format!(
            "{}{}{}{}",
            test_case.prefix,
            test_case.open.repeat(test_case.levels),
            test_case.innermost,
            test_case.close.repeat(test_case.levels),
        );
        let read = test_case.read;
        let error: Option<(String, bool)> = std::thread::Builder::new()
            .stack_size(SMALL_STACK_BYTES)
            .spawn(move || read(&text).map(|error| (error.message, error.syntax)))
            .expect("the parsing thread starts")
            .join()
            .expect("parsing returns rather than panicking");
        assert_eq!(
            error,
            test_case
                .expected_error
                .map(|(message, syntax)| (message.to_owned(), syntax)),
            "{}",
            test_case.description
        );
    }
}
