"""Build coverage/syntax-duckdb/sources.toml and catalogue/<family>.toml from the pinned cache."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from scripts.syntax_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue_duckdb._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue_duckdb._helpers.fetch import pinned
from scripts.syntax_catalogue_duckdb._helpers.indexes import index_rows
from scripts.syntax_catalogue_duckdb._helpers.pages import undecided_pages
from scripts.syntax_catalogue_duckdb.constants import (
    DUCKDB_VERSION,
    FAMILIES,
)
from scripts.syntax_catalogue_duckdb.models import DuckDbCatalogue


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the DuckDB catalogue from the private source cache."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("coverage/syntax-duckdb"))
    parser.add_argument(
        "--draft", action="store_true", help="write the files even when inputs are incomplete"
    )
    arguments: argparse.Namespace = parser.parse_args(argv)
    out: Path = arguments.out
    cache, retrieved_utc = pinned(arguments.cache)
    undecided: list[str] = undecided_pages(cache)
    if undecided:
        print("\n".join(undecided), file=sys.stderr)
        print(
            f"{len(undecided)} page decisions missing; nothing written, even with --draft",
            file=sys.stderr,
        )
        return 1
    built: DuckDbCatalogue = build_catalogue(cache=cache, out=out, retrieved_utc=retrieved_utc)
    if built.problems:
        print("\n".join(built.problems), file=sys.stderr)
        if not arguments.draft:
            print(f"{len(built.problems)} problems; nothing written", file=sys.stderr)
            return 1
        print(f"{len(built.problems)} problems; draft written", file=sys.stderr)
    (out / "catalogue").mkdir(parents=True, exist_ok=True)
    write_tables(
        path=out / "indexes.toml",
        header=f"# The pinned DuckDB {DUCKDB_VERSION} sources: the documentation and railroad "
        "diagrams of\n# duckdb-web, and the PEG grammar of the engine release the omission "
        "audit reads.",
        tables=[
            (
                "index",
                index_rows(cache),
            )
        ],
    )
    write_tables(
        path=out / "sources.toml",
        header=f"# Pinned DuckDB {DUCKDB_VERSION} documentation pages; generated by "
        "scripts/build_syntax_catalogue_duckdb.py.\n# Hashes are of the page's Markdown and "
        "of its rendered diagrams, signatures and type rows. The pages stay private.",
        tables=[("source", built.catalogue.sources)],
    )
    for family in FAMILIES:
        write_tables(
            path=out / "catalogue" / f"{family}.toml",
            header=f"# Documented DuckDB {DUCKDB_VERSION} syntax forms, family {family}; "
            "generated by scripts/build_syntax_catalogue_duckdb.py.",
            tables=[
                ("form", sorted(built.catalogue.forms[family], key=lambda f: str(f["id"]))),
                (
                    "definition",
                    sorted(built.catalogue.definitions[family], key=lambda d: str(d["id"])),
                ),
            ],
        )
    print(json.dumps({family: len(built.catalogue.forms[family]) for family in FAMILIES}))
    return 0
