"""Write coverage/syntax/obligations/<family>.toml from the catalogue grammar and limits.toml."""

from __future__ import annotations

import argparse
from pathlib import Path

from scripts.grammar_catalogue._helpers.toml_out import write_tables
from scripts.grammar_obligations._helpers.elisions import write_elisions
from scripts.grammar_obligations._helpers.obligations import family_obligations, obligation_rows
from scripts.grammar_obligations.types import Row
from scripts.syntax_obligations_snowflake.constants import (
    WITHDRAWN_CLASS_HEADER,
    WITHDRAWN_HEADER,
)


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the obligations of the named families."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("coverage/syntax"))
    parser.add_argument("families", nargs="+")
    arguments: argparse.Namespace = parser.parse_args(argv)
    root: Path = arguments.root
    for family in arguments.families:
        path: Path = root / "obligations" / f"{family}.toml"
        numbered, trees, withdrawn, classes, _ = family_obligations(root=root, family=family)
        write_elisions(root=root, family=family, trees=trees)
        rows: list[Row] = obligation_rows(numbered)
        path.parent.mkdir(parents=True, exist_ok=True)
        write_tables(
            path=path,
            header=f"# Obligations of family {family}; generated by "
            "scripts/build_syntax_obligations.py from the catalogue grammar and limits.toml.\n"
            "# See docs/syntax-coverage.md.",
            tables=[("obligation", rows)],
        )
        withdrawn_path: Path = root / "withdrawn" / f"{family}.toml"
        if withdrawn or classes:
            withdrawn_path.parent.mkdir(parents=True, exist_ok=True)
            write_tables(
                path=withdrawn_path,
                header=WITHDRAWN_HEADER.format(family=family)
                + (WITHDRAWN_CLASS_HEADER if classes else ""),
                tables=[("withdrawn_class", classes), ("withdrawn", withdrawn)],
            )
        elif withdrawn_path.exists():
            withdrawn_path.unlink()
    return 0
