"""Write, or with --check compare, the Snowflake obligations, withdrawn and elisions files."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from scripts.grammar_catalogue._helpers.toml_out import tables_text
from scripts.grammar_obligations._helpers.cases import sync_outputs
from scripts.grammar_obligations._helpers.elisions import elision_outputs
from scripts.grammar_obligations._helpers.obligations import family_obligations, obligation_rows
from scripts.syntax_obligations_snowflake._helpers.changed import changed_families
from scripts.syntax_obligations_snowflake.constants import (
    DEFAULT_ROOT,
    WITHDRAWN_CLASS_HEADER,
    WITHDRAWN_HEADER,
)


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the obligations of the named families, or with --check compare them."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument(
        "--check", action="store_true", help="write nothing; fail when a committed file differs"
    )
    parser.add_argument(
        "--since",
        metavar="REVISION",
        help="build only the families whose inputs changed since the merge base with REVISION",
    )
    parser.add_argument("families", nargs="+")
    arguments: argparse.Namespace = parser.parse_args(argv)
    root: Path = arguments.root
    families: list[str] = arguments.families
    if arguments.since:
        families = changed_families(root=root, base=arguments.since, families=families)
        skipped: list[str] = [f for f in arguments.families if f not in families]
        print(
            f"syntax obligations: {len(families)} families changed since {arguments.since}"
            f"{': ' + ' '.join(families) if families else ''}; skipped {len(skipped)}"
        )
    differing: list[Path] = []
    for family in families:
        differing += sync_outputs(
            outputs=_family_outputs(root=root, family=family), check=arguments.check
        )
    if not arguments.check:
        return 0
    for path in differing:
        print(f"stale: {path} differs from what the build writes", file=sys.stderr)
    print(
        f"syntax obligations: {'FAILED' if differing else 'passed'}, {len(differing)} stale files;"
        " run without --check to regenerate"
    )
    return 1 if differing else 0


def _family_outputs(*, root: Path, family: str) -> list[tuple[Path, str | None]]:
    """The text of each file the build writes for one family (None: no file)."""
    numbered, trees, withdrawn, classes, _ = family_obligations(root=root, family=family)
    obligations: str = tables_text(
        header=f"# Obligations of family {family}; generated by "
        "scripts/build_syntax_obligations.py from the catalogue grammar and limits.toml.\n"
        "# See docs/syntax-coverage.md.",
        tables=[("obligation", obligation_rows(numbered))],
    )
    withdrawals: str | None = (
        tables_text(
            header=WITHDRAWN_HEADER.format(family=family)
            + (WITHDRAWN_CLASS_HEADER if classes else ""),
            tables=[("withdrawn_class", classes), ("withdrawn", withdrawn)],
        )
        if withdrawn or classes
        else None
    )
    return [
        *elision_outputs(root=root, family=family, trees=trees),
        (root / "obligations" / f"{family}.toml", obligations),
        (root / "withdrawn" / f"{family}.toml", withdrawals),
    ]
