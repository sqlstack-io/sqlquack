"""Where a grammar elides content with `...`, and what each elision stands for."""

from __future__ import annotations

import tomllib
from collections.abc import Mapping
from pathlib import Path

from scripts.grammar_catalogue._helpers.toml_out import write_tables
from scripts.grammar_obligations.constants import (
    ELISION_START,
    FAMILY_ELISIONS,
    NODE_OPTIONAL,
    NODE_TOKEN,
    PURE_ELISION,
    TOKEN_ELISION,
    TOKEN_KEYWORD,
)
from scripts.grammar_obligations.exceptions import ObligationError
from scripts.grammar_obligations.models import Node
from scripts.grammar_obligations.types import Row


def is_pure_elision(node: Node) -> bool:
    """A `[ ... ]` optional that holds nothing but an elision: further, unnamed clauses."""
    return node.kind == NODE_OPTIONAL and all(
        len(branch) == 1 and branch[0].token_kind == TOKEN_ELISION for branch in node.branches
    )


def elision_key(*, keywords: list[str], known: Mapping[str, object]) -> str:
    """The rule key of an elision after `keywords`: the last two keywords, else the last one."""
    if len(keywords) > 1 and f"{keywords[-2]} {keywords[-1]}" in known:
        return f"{keywords[-2]} {keywords[-1]}"
    return keywords[-1] if keywords else ELISION_START


def elision_keys(*, nodes: tuple[Node, ...], known: Mapping[str, object]) -> list[str]:
    """The rule key of every standalone or pure elision in one production, in grammar order."""
    keys, _ = _walk(nodes=nodes, known=known, keywords=())
    return keys


def _walk(
    *, nodes: tuple[Node, ...], known: Mapping[str, object], keywords: tuple[str, ...]
) -> tuple[list[str], tuple[str, ...]]:
    """Keys depth first, and the keywords seen; repetitions such as `[ , x ... ]` are lists."""
    keys: list[str] = []
    for node in nodes:
        if is_pure_elision(node):
            keys.append(PURE_ELISION)
        elif node.branches:
            for branch in node.branches:
                if not _is_repetition_branch(branch):
                    found, keywords = _walk(nodes=branch, known=known, keywords=keywords)
                    keys += found
        elif node.token_kind == TOKEN_KEYWORD:
            keywords = (*keywords, node.text.upper())
        elif node.token_kind == TOKEN_ELISION:
            keys.append(elision_key(keywords=list(keywords), known=known))
    return keys, keywords


def _is_repetition_branch(branch: tuple[Node, ...]) -> bool:
    kinds: set[str] = {node.token_kind for node in branch if node.kind == NODE_TOKEN}
    return TOKEN_ELISION in kinds and TOKEN_KEYWORD not in kinds and len(branch) > 1


def write_elisions(*, root: Path, family: str, trees: dict[str, list[tuple[Node, ...]]]) -> None:
    """Write elisions/<family>.toml: each elision, its fill and the forms it defers to."""
    if family not in FAMILY_ELISIONS:
        return
    rules: dict[str, tuple[str, tuple[str, ...], str]] = FAMILY_ELISIONS[family]
    catalogued: set[str] = _catalogued(root=root)
    rows: list[Row] = []
    for form, productions in sorted(trees.items()):
        for production, nodes in enumerate(productions):
            for key in elision_keys(nodes=nodes, known=rules):
                if key not in rules:
                    raise ObligationError(f"{form}: no elision rule after {key!r}")
                fill, defers, reason = rules[key]
                unknown: list[str] = [ref for ref in defers if ref not in catalogued]
                if unknown:
                    raise ObligationError(f"{form}: elision after {key!r} defers to {unknown}")
                rows.append(
                    {
                        "form": form,
                        "production": production,
                        "after": key,
                        "fill": fill,
                        "defers_to": list(defers),
                        "reason": reason,
                    }
                )
    path: Path = root / "elisions" / f"{family}.toml"
    if not rows:
        path.unlink(missing_ok=True)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    write_tables(
        path=path,
        header=f"# Elisions (`...`) in the grammar of family {family}: what each renders as and "
        "the catalogued\n# forms that carry the elided syntax; generated by "
        "scripts/build_syntax_obligations.py.",
        tables=[("elision", rows)],
    )


def _catalogued(*, root: Path) -> set[str]:
    ids: set[str] = set()
    for path in sorted((root / "catalogue").glob("*.toml")):
        ids |= {str(f["id"]) for f in tomllib.loads(path.read_text())["form"]}
    return ids
