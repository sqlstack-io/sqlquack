"""Build coverage/syntax-bigquery/sources.toml and catalogue/<family>.toml from the pinned cache."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from scripts.grammar_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue_bigquery._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue_bigquery._helpers.fetch import grammar_rows, kept_retrieval, pinned
from scripts.syntax_catalogue_bigquery.constants import (
    CATALOGUE_DIR,
    DEFAULT_ROOT,
    FAMILIES,
    INDEXES_FILE,
    INDEXES_HEADER,
    SOURCES_FILE,
    SOURCES_HEADER,
)
from scripts.syntax_catalogue_bigquery.models import BigQueryCatalogue


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the BigQuery catalogue from the private source cache."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path(DEFAULT_ROOT))
    parser.add_argument(
        "--draft", action="store_true", help="write the files even when inputs are incomplete"
    )
    arguments: argparse.Namespace = parser.parse_args(argv)
    out: Path = arguments.out
    cache: Path = pinned(arguments.cache)
    built: BigQueryCatalogue = build_catalogue(cache=cache, out=out)
    if built.problems:
        print("\n".join(built.problems), file=sys.stderr)
        if not arguments.draft:
            print(f"{len(built.problems)} problems; nothing written", file=sys.stderr)
            return 1
        print(f"{len(built.problems)} problems; draft written", file=sys.stderr)
    (out / CATALOGUE_DIR).mkdir(parents=True, exist_ok=True)
    write_tables(
        path=out / SOURCES_FILE,
        header=SOURCES_HEADER,
        tables=[("source", kept_retrieval(path=out / SOURCES_FILE, rows=built.catalogue.sources))],
    )
    write_tables(
        path=out / INDEXES_FILE,
        header=INDEXES_HEADER,
        tables=[("index", grammar_rows(cache))],
    )
    for family in FAMILIES:
        write_tables(
            path=out / CATALOGUE_DIR / f"{family}.toml",
            header=f"# Documented GoogleSQL for BigQuery syntax forms, family {family}; "
            "generated by scripts/build_syntax_catalogue_bigquery.py.",
            tables=[
                ("form", sorted(built.catalogue.forms[family], key=lambda f: str(f["id"]))),
                (
                    "definition",
                    sorted(built.catalogue.definitions[family], key=lambda d: str(d["id"])),
                ),
            ],
        )
    print(json.dumps({family: len(built.catalogue.forms[family]) for family in FAMILIES}))
    return 0
