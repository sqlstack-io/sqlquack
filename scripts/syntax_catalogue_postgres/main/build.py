"""Build coverage/syntax-postgres/sources.toml and catalogue/<family>.toml from the pinned tree."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from scripts.grammar_catalogue._helpers.grammar import sha256
from scripts.grammar_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue_postgres._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue_postgres._helpers.fetch import pinned
from scripts.syntax_catalogue_postgres.constants import (
    FAMILIES,
    INDEX_FILES,
    TARBALL_NAME,
    TARBALL_SHA256,
    TARBALL_URL,
)
from scripts.syntax_catalogue_postgres.models import PgCatalogue


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the PostgreSQL catalogue from the private source cache."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("coverage/syntax-postgres"))
    parser.add_argument(
        "--draft", action="store_true", help="write the files even when inputs are incomplete"
    )
    arguments: argparse.Namespace = parser.parse_args(argv)
    out: Path = arguments.out
    tree, retrieved_utc = pinned(arguments.cache)
    built: PgCatalogue = build_catalogue(tree=tree, out=out, retrieved_utc=retrieved_utc)
    if built.problems:
        print("\n".join(built.problems), file=sys.stderr)
        if not arguments.draft:
            print(f"{len(built.problems)} problems; nothing written", file=sys.stderr)
            return 1
        print(f"{len(built.problems)} problems; draft written", file=sys.stderr)
    (out / "catalogue").mkdir(parents=True, exist_ok=True)
    write_tables(
        path=out / "indexes.toml",
        header="# The pinned PostgreSQL source release (" + TARBALL_URL + ")\n# and the files "
        "in it that list the pages and the grammar: the SQL command reference, the\n# "
        "documentation file lists, gram.y and kwlist.h.",
        tables=[
            (
                "index",
                [{"name": TARBALL_NAME, "sha256": TARBALL_SHA256}]
                + [
                    {"name": name, "sha256": sha256((tree / name).read_text())}
                    for name in INDEX_FILES
                ],
            )
        ],
    )
    write_tables(
        path=out / "sources.toml",
        header="# Pinned PostgreSQL 18.6 documentation pages; generated by "
        "scripts/build_syntax_catalogue_pg.py.\n# A page is a command refentry or a chapter "
        "sect1, read from the release's SGML; hashes are of\n# that SGML text and of its "
        "synopsis blocks and signatures. The pages stay private.",
        tables=[("source", built.catalogue.sources)],
    )
    for family in FAMILIES:
        write_tables(
            path=out / "catalogue" / f"{family}.toml",
            header=f"# Documented PostgreSQL 18.6 syntax forms, family {family}; generated by "
            "scripts/build_syntax_catalogue_pg.py.",
            tables=[
                ("form", sorted(built.catalogue.forms[family], key=lambda f: str(f["id"]))),
                (
                    "definition",
                    sorted(built.catalogue.definitions[family], key=lambda d: str(d["id"])),
                ),
            ],
        )
    print(json.dumps({family: len(built.catalogue.forms[family]) for family in FAMILIES}))
    return 0
