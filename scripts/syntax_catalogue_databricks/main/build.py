"""Build coverage/syntax-databricks/sources.toml, indexes.toml and catalogue/<family>.toml."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from scripts.syntax_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue_databricks._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue_databricks._helpers.fetch import pinned
from scripts.syntax_catalogue_databricks._helpers.indexes import index_rows
from scripts.syntax_catalogue_databricks._helpers.pages import pin_differences, read_page
from scripts.syntax_catalogue_databricks.constants import (
    ARTICLES_FILE,
    CATALOGUE_DIR,
    FAMILIES,
    FORMS_HEADER,
    INDEXES_FILE,
    SOURCES_FILE,
)
from scripts.syntax_catalogue_databricks.models import DbCatalogue


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the Databricks catalogue from the private page cache; nothing on a problem."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("coverage/syntax-databricks"))
    parser.add_argument(
        "--repin",
        action="store_true",
        help="accept pages whose article or Syntax blocks differ from the pins, and re-pin them",
    )
    arguments: argparse.Namespace = parser.parse_args(argv)
    out: Path = arguments.out
    record, retrieved = pinned(arguments.cache)
    urls: list[str] = sorted(record["pages"])  # type: ignore[arg-type]
    if (out / ARTICLES_FILE).exists() and not arguments.repin:
        changed: list[str] = pin_differences(cache=arguments.cache, root=out, urls=urls)
        if changed:
            print("\n".join(changed), file=sys.stderr)
            print(
                f"{len(changed)} pages differ from the pins; nothing written "
                "(--repin accepts them)",
                file=sys.stderr,
            )
            return 1
    later: str = str(record.get("index_linked_retrieved_utc", retrieved))
    built: DbCatalogue = build_catalogue(
        cache=arguments.cache,
        out=out,
        urls=urls,
        retrieved_utc={
            url: later if url in record.get("index_linked", []) else retrieved  # type: ignore[operator]
            for url in urls
        },
    )
    if built.problems:
        print("\n".join(built.problems), file=sys.stderr)
        print(f"{len(built.problems)} problems; nothing written", file=sys.stderr)
        return 1
    (out / CATALOGUE_DIR).mkdir(parents=True, exist_ok=True)
    articles: dict[str, str] = {
        url: read_page(cache=arguments.cache, url=url).article_sha256 for url in urls
    }
    indexes: list[dict[str, str]] = index_rows(record=record, articles=articles)
    write_tables(
        path=out / INDEXES_FILE,
        header="# The Databricks SQL sources: the docs sitemap, the reference page set and the\n"
        "# Apache Spark grammar and parser helpers the omission audit reads. Generated by\n"
        "# scripts/build_syntax_catalogue_databricks.py. The Spark files are pinned by\n"
        "# their hash and the page set by its pages' article hashes; the sitemap's hash is\n"
        "# of the XML as fetched, a record of the fetch rather than a pin.",
        tables=[("index", indexes)],  # type: ignore[list-item]
    )
    write_tables(
        path=out / SOURCES_FILE,
        header="# Databricks SQL language reference pages; generated by\n"
        "# scripts/build_syntax_catalogue_databricks.py. The pins are syntax_sha256, of\n"
        "# the page's Syntax blocks' text, and the article hashes in articles.toml; the\n"
        "# build refuses a page that differs from them unless --repin is given.\n"
        "# page_sha256 is of the HTML as fetched, which names per-deploy script bundles,\n"
        "# so it records the fetch and is not a pin. The pages stay private.",
        tables=[("source", built.sources)],
    )
    write_tables(
        path=out / ARTICLES_FILE,
        header="# The SHA-256 of each pinned page's <article> element, which hand.toml's reviews\n"
        "# bind to and a fetch with --root compares (the rest of a page names per-deploy script\n"
        "# bundles, so its HTML hash changes on every deploy). Generated by\n"
        "# scripts/build_syntax_catalogue_databricks.py.",
        tables=[
            (
                "article",
                [{"url": url, "article_sha256": articles[url]} for url in urls],
            )
        ],  # type: ignore[list-item]
    )
    for family in FAMILIES:
        write_tables(
            path=out / CATALOGUE_DIR / f"{family}.toml",
            header=FORMS_HEADER.format(family=family),
            tables=[
                ("form", sorted(built.forms[family], key=lambda f: str(f["id"]))),
                ("definition", sorted(built.definitions[family], key=lambda d: str(d["id"]))),
            ],
        )
    print(json.dumps({family: len(built.forms[family]) for family in FAMILIES}))
    return 0
