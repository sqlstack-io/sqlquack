"""Build coverage/syntax/sources.toml and coverage/syntax/catalogue/<family>.toml."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from scripts.syntax_catalogue._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue._helpers.grammar import sha256
from scripts.syntax_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue.constants import FAMILIES
from scripts.syntax_catalogue.models import Catalogue


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the catalogue from the private page cache."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("coverage/syntax"))
    arguments: argparse.Namespace = parser.parse_args(argv)
    cache: Path = arguments.cache
    out: Path = arguments.out
    catalogue: Catalogue = build_catalogue(cache=cache, out=out, hand_path=out / "hand.toml")
    (out / "catalogue").mkdir(parents=True, exist_ok=True)
    write_tables(
        path=out / "indexes.toml",
        header="# Documentation indexes the pinned page list was read from (llms.txt files and "
        "the docs navigation tree).",
        tables=[
            (
                "index",
                [
                    {"name": f.name, "sha256": sha256(f.read_text())}
                    for f in sorted((cache / "idx").glob("*"))
                ],
            )
        ],
    )
    write_tables(
        path=out / "sources.toml",
        header="# Pinned Snowflake documentation pages; generated by "
        "scripts/build_syntax_catalogue.py.\n# Hashes are of the fetched page and of its "
        "sqlsyntax blocks; the pages stay private.",
        tables=[("source", catalogue.sources)],
    )
    for family in FAMILIES:
        write_tables(
            path=out / "catalogue" / f"{family}.toml",
            header=f"# Documented Snowflake syntax forms, family {family}; generated by "
            "scripts/build_syntax_catalogue.py.",
            tables=[
                ("form", sorted(catalogue.forms[family], key=lambda f: str(f["id"]))),
                ("definition", sorted(catalogue.definitions[family], key=lambda d: str(d["id"]))),
            ],
        )
    print(json.dumps({family: len(catalogue.forms[family]) for family in FAMILIES}))
    return 0
