"""Build coverage/syntax-sqlite/sources.toml, indexes.toml and catalogue/<family>.toml."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from scripts.syntax_catalogue._helpers.toml_out import write_tables
from scripts.syntax_catalogue_sqlite._helpers.catalogue import build_catalogue
from scripts.syntax_catalogue_sqlite._helpers.fetch import pinned
from scripts.syntax_catalogue_sqlite._helpers.indexes import index_rows
from scripts.syntax_catalogue_sqlite.constants import (
    FAMILIES,
    INDEXES_FILE,
    SOURCES_FILE,
    SQLITE_VERSION,
)
from scripts.syntax_catalogue_sqlite.models import SqliteCatalogue
from scripts.syntax_catalogue_sqlite.types import Row


def run_build(argv: list[str] | None = None) -> int:
    """Regenerate the SQLite catalogue from the private source cache."""
    parser: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("coverage/syntax-sqlite"))
    parser.add_argument(
        "--draft", action="store_true", help="write the files even when inputs are incomplete"
    )
    arguments: argparse.Namespace = parser.parse_args(argv)
    out: Path = arguments.out
    cache, retrieved_utc = pinned(arguments.cache)
    built: SqliteCatalogue = build_catalogue(cache=cache, out=out, retrieved_utc=retrieved_utc)
    if built.problems:
        print("\n".join(built.problems), file=sys.stderr)
        if not arguments.draft:
            print(f"{len(built.problems)} problems; nothing written", file=sys.stderr)
            return 1
        print(f"{len(built.problems)} problems; draft written", file=sys.stderr)
    (out / "catalogue").mkdir(parents=True, exist_ok=True)
    indexes: list[Row] = index_rows(cache)
    write_tables(
        path=out / INDEXES_FILE,
        header=f"# The pinned SQLite {SQLITE_VERSION} sources: the release's documentation, "
        "source and amalgamation\n# archives from sqlite.org, the grammar files the omission "
        "audit reads, the page set and the\n# engine the referee loads. Generated by "
        "scripts/build_syntax_catalogue_sqlite.py.",
        tables=[("index", indexes)],
    )
    pins: str = "".join(f"\n#   {row['sha256']}  {row['name']}" for row in indexes)
    write_tables(
        path=out / SOURCES_FILE,
        header=f"# Pinned SQLite {SQLITE_VERSION} documentation pages; generated by "
        "scripts/build_syntax_catalogue_sqlite.py.\n# Hashes are of the page's HTML in the "
        "documentation archive and of the grammar the page\n# contributes. The pages stay "
        f"private. The pinned archives, grammar files and engine (SHA-256):{pins}",
        tables=[("source", built.catalogue.sources)],
    )
    for family in FAMILIES:
        write_tables(
            path=out / "catalogue" / f"{family}.toml",
            header=f"# Documented SQLite {SQLITE_VERSION} syntax forms, family {family}; "
            "generated by scripts/build_syntax_catalogue_sqlite.py.",
            tables=[
                ("form", sorted(built.catalogue.forms[family], key=lambda f: str(f["id"]))),
                ("definition", []),
            ],
        )
    print(json.dumps({family: len(built.catalogue.forms[family]) for family in FAMILIES}))
    return 0
